/**
 * Generates registry/agent-rules/quill.md — the `@quill/agent-rules` item, a
 * `registry:file` the shadcn CLI writes to `.claude/rules/quill.md` at a
 * consumer app's project root, where Claude Code loads it every session.
 *
 * Why this exists: the shadcn MCP strips `docs` and `meta` before an agent
 * sees an item, so inside an app nothing tells the agent Quill's rules or
 * even which blocks exist — the weekly pattern scan kept finding blocks Quill
 * ships rebuilt by hand. A rules file on disk is the one durable channel.
 *
 * Nothing here is written twice. The theming contract comes from
 * src/usage/theme-docs.mjs (the base item's install docs), the foundations and
 * principles from src/usage/foundations.mjs (the same renderer that fills
 * llms.txt and DESIGN.md), the icon names from the generated core map, the
 * block index from registry.json. Run BEFORE `build:registry`, which inlines
 * the file's content into public/r/agent-rules.json.
 * `scripts/build-agent-rules.test.mjs` fails CI when the committed file is stale.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

import { icons } from '../src/components/ui/icons.core.mjs'
import { themeDocsParagraphs, LLMS_URL } from '../src/usage/theme-docs.mjs'
import { renderFoundations, renderPrinciples } from '../src/usage/foundations.mjs'
import { ALL_USAGE } from '../src/usage/index.mjs'
import { INTENT_TAGS } from './registry-intent-tags.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const RULES_PATH = join(root, 'registry/agent-rules/quill.md')

export function renderAgentRules() {
  const registry = JSON.parse(readFileSync(join(root, 'registry.json'), 'utf8'))
  const HOME = registry.homepage.replace(/\/$/, '')
  const blocks = registry.items.filter((i) => i.type === 'registry:block')
  const coreNames = Object.keys(icons).sort()
  const L = []
  const p = (s = '') => L.push(s)

  p('# Quill design system — rules for this app')
  p()
  // No version stamp on purpose: the file must change only when its content
  // does, or every patch release would push a rules-only sync PR into every app.
  p('<!-- Generated by quill-ds (scripts/build-agent-rules.mjs). Do not edit by hand: update with `npx shadcn@latest add @quill/agent-rules --overwrite`. -->')
  p()
  p(`This app is built on Quill (${HOME}): a token layer with five themes and four accents, two shipped components (\`icon\`, \`tone-badge\`) and ${blocks.length} blocks, installed through the shadcn CLI. Read this before touching UI. Full reference: ${LLMS_URL}. Per-component rules: \`${HOME}/usage/<name>.md\`.`)
  p()

  p('## Theming contract')
  p()
  for (const para of themeDocsParagraphs()) p(`- ${para}`)
  p()

  p('## Foundations')
  p()
  p(renderFoundations())
  p()

  p('## Principles')
  p()
  p(renderPrinciples({ blockCount: blocks.length }))
  p()

  p('## Icons')
  p()
  p(`\`<Icon name="…">\` from \`components/ui/icon.tsx\` renders Material Symbols Outlined at weight 400. Only the core set ships to this app (${coreNames.length} names); any other name renders an empty, size-reserved box and a console warning in development. Decorative by default (\`aria-hidden\`); pass \`aria-label\` only when the icon stands alone. Core names:`)
  p()
  p(coreNames.join(', '))
  p()

  p('## Blocks — reach for one before building')
  p()
  p(`Install: \`npx shadcn@latest add @quill/<name>\`. Update: add \`--overwrite\`. Grouped by primary intent. Every block has a usage guide at \`${HOME}/usage/<name>.md\` (when to use, what to reach for instead, rules, accessibility) — read it before installing.`)
  p()
  const byIntent = new Map()
  for (const b of blocks) {
    const intent = b.meta?.intent?.[0] ?? 'other'
    if (!byIntent.has(intent)) byIntent.set(intent, [])
    byIntent.get(intent).push(b)
  }
  for (const [tag, def] of Object.entries(INTENT_TAGS)) {
    const list = byIntent.get(tag)
    if (!list?.length) continue
    p(`- **${tag}** — ${def}`)
    for (const b of list) p(`  - \`${b.name}\` — ${b.title ?? b.name}`)
  }
  for (const [tag, list] of byIntent) {
    if (INTENT_TAGS[tag]) continue
    p(`- **${tag}**`)
    for (const b of list) p(`  - \`${b.name}\` — ${b.title ?? b.name}`)
  }
  p()

  const primitives = ALL_USAGE.filter((u) => u.kind === 'component').map((u) => u.name)
  p('## Primitives')
  p()
  p(`Stock shadcn components restyled by the token layer — install them from shadcn (\`npx shadcn@latest add button\`), never hand-roll them. Quill-specific usage rules exist at \`${HOME}/usage/<name>.md\` for: ${primitives.join(', ')}.`)
  p()

  p('## Updating and verifying')
  p()
  p('- Theme: `npx shadcn@latest add @quill/quill --overwrite`. Blocks: `npx shadcn@latest add @quill/<name> --overwrite`. This file: `npx shadcn@latest add @quill/agent-rules --overwrite`. `--yes` does not overwrite a changed file — it prompts in a terminal and silently skips when non-interactive.')
  p('- After UI changes: `npx tsc --noEmit`, `npm run lint`, then switch `data-theme` and `data-accent` on `<html>` and confirm both take effect.')
  p()
  return L.join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(dirname(RULES_PATH), { recursive: true })
  writeFileSync(RULES_PATH, renderAgentRules())
  console.log('wrote registry/agent-rules/quill.md')
}
